import type { AuditResult, PageData } from '../types.js';
import { estimateTokens, truncateToTokens } from '../analyzer/token-counter.js';
import { factsOf } from '../extractor/page-classifier.js';

const line = (p: PageData) => `- [${p.title || p.h1 || p.url}](${p.url})${p.summary ? ': ' + p.summary.replace(/\s+/g, ' ') : ''}`;

export function buildLlmsTxt(r: AuditResult, maxTokens = 6000): string {
  const ok = r.pages.filter((p) => p.status === 200);
  const home = ok.find((p) => { try { return new URL(p.url).pathname === '/'; } catch { return false; } }) ?? ok[0];
  const core = ok.filter((p) => p.tier === 1 && p !== home);
  const tier2 = ok.filter((p) => p.tier === 2);
  const catalog = [...tier2.filter((p) => p.products.length === 0), ...tier2.filter((p) => p.products.length > 0)].map(line);

  const head: string[] = [`# ${r.siteName}`, '', `> ${home?.description || home?.summary || r.siteName + ' official website.'}`, ''];
  const facts: string[] = [];
  if (r.nap.phone) facts.push(`- Phone: ${r.nap.phone}`);
  if (r.nap.email) facts.push(`- Email: ${r.nap.email}`);
  if (r.nap.address) facts.push(`- Address: ${r.nap.address}`);
  if (r.rating) facts.push(`- Customer rating: ${r.rating.value}${r.rating.count ? ` (${r.rating.count} reviews)` : ''}`);
  if (facts.length) head.push('Key facts:', ...facts, '');

  const coreLines = [home, ...core].filter(Boolean).map((p) => line(p as PageData));
  const socialLines = r.social.map((s) => `- [${s.platform}](${s.url}): official ${s.platform} channel of ${r.siteName}`);
  const tail: string[] = ['## Optional', `- [Full knowledge base](${r.origin}/llms-full.txt): cleaned Markdown of the most important pages`, ''];

  const assemble = (cat: string[]) => {
    const parts = [...head];
    if (coreLines.length) parts.push('## Core Pages', ...coreLines, '');
    if (cat.length) parts.push('## Key Products, Categories & Buying Guides', ...cat, '');
    if (socialLines.length) parts.push('## Official Brand Channels, Social Proof & Authority', ...socialLines, '');
    parts.push(...tail);
    return parts.join('\n').replace(/\n{3,}/g, '\n\n').trimEnd() + '\n';
  };

  let cat = catalog;
  let out = assemble(cat);
  while (estimateTokens(out) > maxTokens && cat.length > 0) {
    cat = cat.slice(0, Math.floor(cat.length * 0.8) === cat.length ? cat.length - 1 : Math.floor(cat.length * 0.8));
    out = assemble(cat);
  }
  if (estimateTokens(out) > maxTokens) out = truncateToTokens(out, maxTokens) + '\n';
  return out;
}

export interface FullStats { tokens: number; pages: number; truncated: number; factsOnly: number }

export function buildLlmsFull(r: AuditResult, maxTokens = 80000): { text: string; stats: FullStats } {
  const ok = r.pages.filter((p) => p.status === 200 && p.tier !== 3);
  const ordered = [
    ...ok.filter((p) => p.tier === 1),
    ...ok.filter((p) => p.tier === 2 && p.products.length === 0),
    ...ok.filter((p) => p.tier === 2 && p.products.length > 0)
  ];
  const stats: FullStats = { tokens: 0, pages: 0, truncated: 0, factsOnly: 0 };
  const out: string[] = [`# ${r.siteName}: full knowledge base`, '', `> Generated by geoforge from ${r.origin}. Tier 1 pages first, then Tier 2.`, ''];
  let used = estimateTokens(out.join('\n'));
  for (const p of ordered) {
    const facts = factsOf(p.products) || p.summary;
    const header = ['---', `URL: ${p.url}`, `Tier: ${p.tier}`, `Tokens: ${p.tokens}`, ...(facts ? [`Extracted Facts/Price: ${facts}`] : []), '---', ''].join('\n');
    const full = `${header}\n${p.markdown}\n\n`;
    const remaining = maxTokens - used;
    if (estimateTokens(full) <= remaining) {
      out.push(full); used += estimateTokens(full); stats.pages++;
    } else if (p.products.length > 0) {
      const compact = `${header}\n# ${p.title}\n${facts}\n\n`;
      if (estimateTokens(compact) <= remaining) { out.push(compact); used += estimateTokens(compact); stats.pages++; stats.factsOnly++; }
    } else if (remaining > 600) {
      const cut = truncateToTokens(full, remaining - 20) + '\n\n[truncated by geoforge token budget]\n\n';
      out.push(cut); used += estimateTokens(cut); stats.pages++; stats.truncated++;
    }
  }
  const text = out.join('\n');
  stats.tokens = estimateTokens(text);
  return { text, stats };
}
