import type { BotRule, BotStatus, RobotsAnalysis } from '../types.js';

export const SEARCH_BOTS = [
  { bot: 'OAI-SearchBot', vendor: 'OpenAI (ChatGPT Search)' },
  { bot: 'ChatGPT-User', vendor: 'OpenAI (live user browsing)' },
  { bot: 'Claude-SearchBot', vendor: 'Anthropic (web search)' },
  { bot: 'Claude-User', vendor: 'Anthropic (live user fetch)' },
  { bot: 'PerplexityBot', vendor: 'Perplexity' },
  { bot: 'Perplexity-User', vendor: 'Perplexity (live user fetch)' },
  { bot: 'Applebot', vendor: 'Apple Intelligence search' }
];
export const TRAINING_BOTS = [
  { bot: 'GPTBot', vendor: 'OpenAI (training)' },
  { bot: 'ClaudeBot', vendor: 'Anthropic (training)' },
  { bot: 'Google-Extended', vendor: 'Google (Gemini training)' },
  { bot: 'CCBot', vendor: 'Common Crawl' },
  { bot: 'Meta-ExternalAgent', vendor: 'Meta (training)' },
  { bot: 'Bytespider', vendor: 'ByteDance (training)' },
  { bot: 'Amazonbot', vendor: 'Amazon' }
];

interface Group { agents: string[]; rules: { type: 'allow' | 'disallow'; path: string }[] }

export function parseRobotsTxt(text: string): { groups: Group[]; sitemaps: string[] } {
  const groups: Group[] = [];
  const sitemaps: string[] = [];
  let cur: Group | null = null;
  let lastWasAgent = false;
  for (const raw of text.split(/\r?\n/)) {
    const line = raw.replace(/#.*$/, '').trim();
    if (!line) continue;
    const idx = line.indexOf(':');
    if (idx < 0) continue;
    const key = line.slice(0, idx).trim().toLowerCase();
    const value = line.slice(idx + 1).trim();
    if (key === 'user-agent') {
      if (!cur || !lastWasAgent) { cur = { agents: [], rules: [] }; groups.push(cur); }
      cur.agents.push(value.toLowerCase());
      lastWasAgent = true;
    } else if (key === 'allow' || key === 'disallow') {
      if (cur) cur.rules.push({ type: key, path: value });
      lastWasAgent = false;
    } else if (key === 'sitemap') {
      sitemaps.push(value);
      lastWasAgent = false;
    } else {
      lastWasAgent = false;
    }
  }
  return { groups, sitemaps };
}

function blocksRoot(g: Group): boolean {
  const dis = g.rules.some((r) => r.type === 'disallow' && r.path === '/');
  const allow = g.rules.some((r) => r.type === 'allow' && (r.path === '/' || r.path === ''));
  return dis && !allow;
}

export function botStatus(groups: Group[], bot: string): BotStatus {
  const specific = groups.find((g) => g.agents.includes(bot.toLowerCase()));
  if (specific) return blocksRoot(specific) ? 'Blocked' : 'Allowed';
  const wildcard = groups.find((g) => g.agents.includes('*'));
  if (wildcard && blocksRoot(wildcard)) return 'Blocked';
  return 'Unspecified';
}

export function analyzeRobots(text: string | null): RobotsAnalysis {
  const found = text !== null && text.trim().length > 0;
  const { groups, sitemaps } = found ? parseRobotsTxt(text as string) : { groups: [], sitemaps: [] };
  const bots: BotRule[] = [
    ...SEARCH_BOTS.map((b) => ({ ...b, group: 'search' as const, status: botStatus(groups, b.bot) })),
    ...TRAINING_BOTS.map((b) => ({ ...b, group: 'training' as const, status: botStatus(groups, b.bot) }))
  ];
  const issues: string[] = [];
  if (!found) issues.push('robots.txt not found: AI bots are allowed by default, but you cannot control training scrapers or junk URLs.');
  for (const b of bots.filter((x) => x.group === 'search' && x.status === 'Blocked')) {
    issues.push(`${b.bot} (${b.vendor}) is BLOCKED: you lose citations and traffic from this AI search engine.`);
  }
  const trainingOpen = bots.filter((x) => x.group === 'training' && x.status !== 'Blocked').map((x) => x.bot);
  if (found && trainingOpen.length > 0) issues.push(`Training scrapers not blocked (owner choice): ${trainingOpen.join(', ')}.`);
  return { found, bots, sitemaps, issues };
}

export const JUNK_PATHS = ['/cart', '/checkout', '/basket', '/account', '/login', '/admin', '/wp-admin/', '/search', '/*?add-to-cart=', '/*?sort=', '/*?filter=', '/*?utm_'];

export function generateRobotsAi(opts: { origin: string; allowTraining?: boolean; sitemaps?: string[] }): string {
  const L: string[] = [];
  L.push('# robots.ai.txt generated by geoforge');
  L.push('# Merge these groups into your /robots.txt');
  L.push('');
  L.push('# AI Search and Citation bots: they send traffic and buyers, keep them allowed');
  for (const b of SEARCH_BOTS) L.push(`User-agent: ${b.bot}`);
  L.push('Allow: /');
  for (const p of JUNK_PATHS) L.push(`Disallow: ${p}`);
  L.push('');
  L.push(opts.allowTraining ? '# AI Training scrapers: allowed by owner choice (--allow-training)' : '# AI Training scrapers: blocked by default (use --allow-training to open)');
  for (const b of TRAINING_BOTS) L.push(`User-agent: ${b.bot}`);
  if (opts.allowTraining) {
    L.push('Allow: /');
    for (const p of JUNK_PATHS) L.push(`Disallow: ${p}`);
  } else {
    L.push('Disallow: /');
  }
  L.push('');
  L.push('# Everyone else');
  L.push('User-agent: *');
  for (const p of JUNK_PATHS) L.push(`Disallow: ${p}`);
  L.push('');
  const maps = opts.sitemaps && opts.sitemaps.length ? opts.sitemaps : [`${opts.origin}/sitemap.xml`];
  for (const s of maps) L.push(`Sitemap: ${s}`);
  L.push(`# llms.txt: ${opts.origin}/llms.txt`);
  return L.join('\n') + '\n';
}
